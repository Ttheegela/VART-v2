SAMPLE = (
    "# Access Control Policy\n\n"
    "User access to internal systems is reviewed quarterly.\n\n"
    "- MFA is required.\n\n"
    "| System | Owner |\n|---|---|\n| Okta | Dana Ortiz |\n"
)
SPEC = {
    "sheet": "Access reviews",
    "title": "Kestrelyn access review log",
    "as_of": "2026-09-15",
    "headers": ["System", "Status"],
    "rows": [["Okta", "Overdue"]],
}


def test_parse_md_blocks() -> None:
    assert parse_md(SAMPLE) == [
        ("h", 1, "Access Control Policy"),
        ("p", "User access to internal systems is reviewed quarterly."),
        ("li", "MFA is required."),
        ("table", ("System", "Owner"), (("Okta", "Dana Ortiz"),)),
    ]


def test_docx_and_pdf_keep_every_sentence(tmp_path: Path) -> None:
    for render_one, name in ((render_docx, "a.docx"), (render_pdf, "a.pdf")):
        path = tmp_path / name
        render_one(parse_md(SAMPLE), path)
        text = text_of(path)
        assert contains(text, "User access to internal systems is reviewed quarterly.")
        assert contains(text, "System: Okta; Owner: Dana Ortiz")


def test_xlsx_records(tmp_path: Path) -> None:
    path = tmp_path / "a.xlsx"
    render_xlsx(SPEC, path)
    assert "System: Okta; Status: Overdue" in text_of(path)
    assert "As of: 2026-09-15" in text_of(path)


def test_render_is_deterministic(tmp_path: Path) -> None:
    a = render_pack("dev", tmp_path / "a")
    b = render_pack("dev", tmp_path / "b")

    def digest(paths: list[Path]) -> list[str]:
        return [hashlib.sha256(p.read_bytes()).hexdigest() for p in paths]

    assert digest(a) == digest(b)


def _sample_files(folder: Path) -> list[Path]:
    render_docx(parse_md(SAMPLE), folder / "a.docx")
    render_pdf(parse_md(SAMPLE), folder / "a.pdf")
    render_xlsx(SPEC, folder / "a.xlsx")
    return [folder / "a.docx", folder / "a.pdf", folder / "a.xlsx"]


def test_bytes_do_not_depend_on_the_clock(tmp_path: Path) -> None:
    first = _sample_files(tmp_path / "first")
    time.sleep(1.1)  # the formats stamp whole seconds
    second = _sample_files(tmp_path / "second")
    assert [p.read_bytes() for p in first] == [p.read_bytes() for p in second]


def test_office_zips_are_stored_and_pdfs_are_not_compressed(tmp_path: Path) -> None:
    docx_path, pdf_path, xlsx_path = _sample_files(tmp_path)
    for path in (docx_path, xlsx_path):  # normalize_zip: no zlib, one creating OS, no tool name
        with zipfile.ZipFile(path) as z:
            assert {i.compress_type for i in z.infolist()} == {zipfile.ZIP_STORED}, path.name
            assert {i.create_system for i in z.infolist()} == {3}, path.name
            assert {i.date_time for i in z.infolist()} == {(2026, 1, 1, 0, 0, 0)}, path.name
            assert b"<Application>" not in z.read("docProps/app.xml"), path.name
    assert b"FlateDecode" not in pdf_path.read_bytes()  # compressed streams would depend on the zlib build
    assert docx.Document(str(docx_path)).core_properties.comments == ""  # no "generated by python-docx"


