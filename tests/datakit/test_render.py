def test_the_docs_stage_flags_a_stale_file_a_missing_file_and_non_ascii_source(pack: Path) -> None:
    (pack / "docs" / "security-faq.md").write_text("changed\n")
    (pack / "docs" / "bcp-dr-plan.docx").unlink()
    (pack / "src" / "wiki.md").write_text("café\n", encoding="utf-8")
    found = STAGES["docs"]("dev")
    assert "missing rendered file bcp-dr-plan.docx" in found
    assert "wiki.md is not ASCII" in found
    assert "security-faq.md is stale: run python -m datakit.render dev" in found
    assert not [p for p in found if "bcp-dr-plan.docx is stale" in p]  # reported once, as missing


def _units(path: Path) -> list[str]:
    lines = lines_of(path)
    if path.suffix == ".pdf":  # one long line per PDF: split into sentences
        return [
            s.strip() + ("" if s.strip().endswith(".") else ".") for s in lines[0].split(". ") if s.strip()
        ]
    return lines


def test_no_unregistered_control_keywords() -> None:
    facts = load_yaml(DATA / "dev" / "facts.yaml", Facts)
    allowed_file = DATA / "dev" / "src" / "ALLOWED_LINES.txt"
    allowed = {ln.split(" # ")[0].strip() for ln in allowed_file.read_text().splitlines() if ln.strip()}
    loose = []
    for d in facts.documents:
        registered = [s.text for s in facts.statements if s.doc == d.id]
        for unit in _units(DATA / "dev" / "docs" / d.filename):
            if (
                CONTROL_WORDS.search(unit)
                and unit not in allowed
                and not any(r in unit or unit in r for r in registered)
            ):
                loose.append(f"{d.filename}: {unit[:120]}")
    assert loose == []


# Leak sentences that a reviewer used to probe the keyword net; each one must be flagged. Three of them use
# acronyms that only match as whole words; the last three use an un- prefix, a plural acronym and a hyphenated
# phrase.
PROBES = (
    "Office key-fob access is logged.",
    "A diagram of how customer data moves is maintained.",
    "HSTS and CSP response headers are set.",
    "Developers are trained on injection flaws.",
    "Customers sign in using OIDC.",
    "Kestrelyn holds cyber liability coverage of USD 10,000,000.",
    "Reports go to the security@ mailbox.",
    "Employees sign in through SSO.",
    "Reports are shared under an NDA.",
    "The contract includes an SLA.",
    "Laptop disks are unencrypted.",
    "Reports are shared under NDAs.",
    "We run a bug-bounty program.",
)
# Words that merely contain an acronym: "sso", "nda" and "sla" are inside them.
LOOKALIKES = ("lesson", "association", "agenda", "islands")


def test_the_keyword_net_flags_every_probe_sentence() -> None:
    assert [p for p in PROBES if not CONTROL_WORDS.search(p)] == []
    assert CONTROL_WORDS.search("Access is reviewed.")  # a stem matches at a word start, with any ending
    words = [*CONTROL_STEMS, *CONTROL_ACRONYMS]
    variants = [v for w in words for v in (w, w.replace(" ", "-"), w.replace("-", " "))]
    unmatched = [v for v in variants if not CONTROL_WORDS.search(v)]
    assert unmatched == []  # every stem and acronym finds itself, with a space or a hyphen between its words


def test_the_keyword_net_does_not_match_inside_words() -> None:
    sentence = "The association shared the lesson and the agenda on the islands."
    assert [t for t in (*LOOKALIKES, sentence) if CONTROL_WORDS.search(t)] == []
    assert not CONTROL_WORDS.search("A preview of the roadmap.")  # "review" is a stem, not a substring
