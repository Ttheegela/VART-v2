@pytest.fixture
def pack(tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> Path:
    """A rendered copy of the dev pack that the docs stage and the renderer both read instead of data/."""
    root = tmp_path / "data" / "dev"
    root.mkdir(parents=True)
    shutil.copy(DATA / "dev" / "facts.yaml", root / "facts.yaml")
    shutil.copytree(DATA / "dev" / "src", root / "src")
    monkeypatch.setattr(render, "ROOT", tmp_path)
    monkeypatch.setattr(validate, "DATA", tmp_path / "data")
    render_pack("dev")
    return root


def test_the_docs_stage_flags_a_sentence_split_across_lines(pack: Path) -> None:
    assert STAGES["docs"]("dev") == []
    source = pack / "src" / "dcp.md"
    source.write_text(source.read_text().replace("deleted within 30 days", "deleted\n\nwithin 30 days"))
